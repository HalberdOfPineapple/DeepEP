#!/usr/bin/env python3
"""Apply the tracing patch to the private copy of DeepEP's dispatch kernel.

The repo and the installed package are never modified. The patch is applied to
  experiments/observability-exploration/common/pkg/deep_ep/include/deep_ep/impls/ep/dispatch.cuh
starting from the pristine upstream text (taken from the installed package, identical to commit 93eb6eb).

Trace records are written through the `cumulative_local_expert_recv_stats` pointer: the host passes a
1-D int32 view of length num_local_experts whose underlying allocation is much larger; the kernel writes
its records after the first num_local_experts ints. Layout (int64 units, relative to the first int64 after
the stats):

  HDR   [0, 16)            host-written header: magic, num_tokens, kNumSMs, kNumDispatchWarps, kNumTopk, variant flags
  SM    [16, 1040)         32 slots per SM (up to 32 SMs): kernel entry, barrier arrive/release, notify phases
  SEND  [1040, 3088)       phase E: timestamp right after put_value of receive slot i (SM 0 thread owning i)
  RECV  [3088, 5136)       phase F: timestamp when receive slot i was first seen ready (same thread)
  WARP  [5136, 7184)       4 per dispatch warp: first loop entry, last store completion, tokens handled, SM id
  TOK   [8192, 8192+64*T)  64 per token, see TOK_* constants in trace_layout.py

Variants (compile-time; the file content is part of DeepJIT's cache key so a change triggers recompilation):
  --wait-read        use cp.async.bulk.wait_group.read in the loop (slot free when source bytes are read)
  --pad-counters     give each slot counter its own 128 B line (stride 32 ints)
  --relocate-recv N  move the receive-count array N bytes into the unused hybrid signal region
  --no-trace         variants without the per-token trace (to measure the probe cost)
"""
import argparse, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
PKG = os.path.join(HERE, 'pkg', 'deep_ep', 'include', 'deep_ep', 'impls', 'ep', 'dispatch.cuh')
PRISTINE = os.path.join(HERE, 'dispatch.cuh.pristine')


def sub_once(s, old, new, label):
    assert s.count(old) == 1, f'patch anchor not unique/missing: {label} (count={s.count(old)})'
    return s.replace(old, new)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--wait-read', action='store_true')
    ap.add_argument('--pad-counters', action='store_true')
    ap.add_argument('--relocate-recv', type=int, default=0, help='byte offset into scaleout_channel_signaled_tail')
    ap.add_argument('--no-trace', action='store_true')
    ap.add_argument('--pristine', action='store_true', help='restore the unpatched kernel')
    ap.add_argument('--no-sm', action='store_true'); ap.add_argument('--no-notify', action='store_true'); ap.add_argument('--no-loop', action='store_true')
    a = ap.parse_args()

    if not os.path.exists(PRISTINE):
        import shutil; shutil.copy(PKG, PRISTINE)
    s = open(PRISTINE).read()
    if a.pristine:
        open(PKG, 'w').write(s); print('restored pristine dispatch.cuh'); return

    TRACE = 0 if a.no_trace else 1
    header = f'''
// ===== observability-exploration trace patch (generated by apply_trace_patch.py) =====
#define EP_TRACE {TRACE}
#define EP_TRACE_WAIT_READ {int(a.wait_read)}
#define EP_TRACE_PAD_COUNTERS {int(a.pad_counters)}
#define EP_TRACE_RELOCATE_RECV {a.relocate_recv}
#define EP_TRACE_SM {int(not a.no_sm)}
#define EP_TRACE_NOTIFY {int(not a.no_notify)}
#define EP_TRACE_LOOP {int(not a.no_loop)}
namespace deep_ep::ep::trace {{
__device__ __forceinline__ int64_t now() {{ uint64_t t; asm volatile("mov.u64 %0, %globaltimer;" : "=l"(t)); return static_cast<int64_t>(t); }}
__device__ __forceinline__ int64_t smid() {{ unsigned s; asm volatile("mov.u32 %0, %smid;" : "=r"(s)); return static_cast<int64_t>(s); }}
__device__ __forceinline__ int64_t cycles() {{ uint64_t t; asm volatile("mov.u64 %0, %clock64;" : "=l"(t)); return static_cast<int64_t>(t); }}
constexpr int kHdr = 0, kSM = 16, kSend = 1040, kRecv = 3088, kWarp = 5136, kTok = 8192, kTokStride = 64;
constexpr int kCounterStride = EP_TRACE_PAD_COUNTERS ? 32 : 1;
}}  // namespace deep_ep::ep::trace
// =====================================================================================
'''
    s = sub_once(s, 'namespace deep_ep::ep {\n\ntemplate <bool kIsScaleupNVLink,', header + '\nnamespace deep_ep::ep {\n\ntemplate <bool kIsScaleupNVLink,', 'header')

    # --- trace base pointer, kernel entry timestamp ---
    s = sub_once(s, '''    // Named barrier indices
    constexpr int kNotifyBarrierIndex = 1;
''', '''    // Named barrier indices
    constexpr int kNotifyBarrierIndex = 1;

#if EP_TRACE
    // Trace region lives after the first kNumExpertsPerRank ints of the stats tensor (host allocates the rest)
    int64_t* const TR = (cumulative_local_expert_recv_stats != nullptr) ?
        reinterpret_cast<int64_t*>(cumulative_local_expert_recv_stats + kNumExpertsPerRank) : nullptr;
    const bool tr_on = TR != nullptr and TR[trace::kHdr] == 0x4550545243ll;
    if (tr_on and thread_idx == 0) TR[trace::kSM + sm_idx * 32 + 0] = trace::now();
#endif
''', 'trace base')

    # --- opening barrier timestamps (arrive = before call, release = after) ---
    s = sub_once(s, '''    // Barrier without TMA store flush, without prologue grid sync
    comm::gpu_barrier<kIsScaleupNVLink, 1, kNumRanks,
                      kNumSMs, kNumThreads, kNumQPs, kNumTimeoutCycles, comm::kDispatchTag0, false, false, true>(
        gin, workspace_layout.get_barrier_signals(), 0, rank_idx, sm_idx, thread_idx);
''', '''    // Barrier without TMA store flush, without prologue grid sync
#if EP_TRACE && EP_TRACE_SM
    if (tr_on and thread_idx == 0) TR[trace::kSM + sm_idx * 32 + 1] = trace::now();
#endif
    comm::gpu_barrier<kIsScaleupNVLink, 1, kNumRanks,
                      kNumSMs, kNumThreads, kNumQPs, kNumTimeoutCycles, comm::kDispatchTag0, false, false, true>(
        gin, workspace_layout.get_barrier_signals(), 0, rank_idx, sm_idx, thread_idx);
#if EP_TRACE && EP_TRACE_SM
    if (tr_on and thread_idx == 0) TR[trace::kSM + sm_idx * 32 + 2] = trace::now();
#endif
''', 'opening barrier')

    # --- notify: phase C done (all SMs), D done, E issue per slot, F per slot, H done ---
    s = sub_once(s, '''            ptx::red_add(workspace_layout.get_notify_reduction_workspace_ptr() + i, counter);
        }

        // Do the remaining work by SM 0
        if (sm_idx == 0) {
''', '''            ptx::red_add(workspace_layout.get_notify_reduction_workspace_ptr() + i, counter);
        }
#if EP_TRACE && EP_TRACE_SM
        if (tr_on and thread_idx == 0) TR[trace::kSM + sm_idx * 32 + 3] = trace::now();
#endif

        // Do the remaining work by SM 0
        if (sm_idx == 0) {
''', 'phase C')
    s = sub_once(s, '''            ptx::named_barrier<kNumNotifyThreads>(kNotifyBarrierIndex);

            // TODO: for further optimization, we can fuse rank and expert counters
            // Issue scaleup rank count writes to peers
            for (int i = thread_idx; i < kNumRanks; i += kNumNotifyThreads) {
                // Rank counters
                const auto dst_rank_counter =
                    workspace_layout.get_scaleup_rank_count_ptr<false>() + rank_idx;
                gin.put_value<team_t>(dst_rank_counter, static_cast<int64_t>(rank_count[i]), i,
                                      ncclGinOptFlagsAggregateRequests);
            }
            __syncwarp();
''', '''            ptx::named_barrier<kNumNotifyThreads>(kNotifyBarrierIndex);
#if EP_TRACE && EP_TRACE_NOTIFY
            if (tr_on and thread_idx == 0) TR[trace::kSM + 4] = trace::now();
#endif

            // TODO: for further optimization, we can fuse rank and expert counters
            // Issue scaleup rank count writes to peers
            for (int i = thread_idx; i < kNumRanks; i += kNumNotifyThreads) {
                // Rank counters
                const auto dst_rank_counter =
                    RECV_COUNT_PTR() + rank_idx;
                gin.put_value<team_t>(dst_rank_counter, static_cast<int64_t>(rank_count[i]), i,
                                      ncclGinOptFlagsAggregateRequests);
#if EP_TRACE && EP_TRACE_NOTIFY
                // slot index in the receiver's array for this write is rank_idx (rank counts occupy [0, kNumRanks))
                if (tr_on) TR[trace::kSend + i * 0 + rank_idx] = trace::now();
#endif
            }
            __syncwarp();
''', 'phase E rank')
    s = sub_once(s, '''                for (int i = thread_idx; i < kNumExperts; i += kNumNotifyThreads) {
                    const auto idx = kNumExpertsPerRank * rank_idx + (i % kNumExpertsPerRank);
                    gin.put_value<team_t>(
                        workspace_layout.get_scaleup_expert_count_ptr<false>() + idx,
                        static_cast<int64_t>(expert_count[i]), i / kNumExpertsPerRank);
                }
''', '''                for (int i = thread_idx; i < kNumExperts; i += kNumNotifyThreads) {
                    const auto idx = kNumExpertsPerRank * rank_idx + (i % kNumExpertsPerRank);
                    gin.put_value<team_t>(
                        RECV_COUNT_PTR() + kNumRanks + idx,
                        static_cast<int64_t>(expert_count[i]), i / kNumExpertsPerRank);
#if EP_TRACE && EP_TRACE_NOTIFY
                    // receiver slot = kNumRanks + idx; the destination rank is i / kNumExpertsPerRank. Record per sent expert i.
                    if (tr_on) TR[trace::kSend + kNumRanks + i] = trace::now();
#endif
                }
''', 'phase E expert')
    s = sub_once(s, '''                for (int i = thread_idx; i < kNumRanks; i += kNumNotifyThreads) {
                    const auto src_ptr = workspace_layout.get_scaleup_expert_count_ptr<true>() + kNumExpertsPerRank * i;
                    const auto dst_ptr = workspace_layout.get_scaleup_expert_count_ptr<false>() + kNumExpertsPerRank * rank_idx;
''', '''                for (int i = thread_idx; i < kNumRanks; i += kNumNotifyThreads) {
                    const auto src_ptr = workspace_layout.get_scaleup_expert_count_ptr<true>() + kNumExpertsPerRank * i;
                    const auto dst_ptr = RECV_COUNT_PTR() + kNumRanks + kNumExpertsPerRank * rank_idx;
''', 'phase E rdma')
    s = sub_once(s, '''            // Wait for rank and expert count
            const auto start_clock = clock64();
            for (int i = thread_idx; i < kNumRanks + kNumExperts; i += kNumNotifyThreads) {
                comm::timeout_while<kNumTimeoutCycles>([=](const bool& is_last_check) {
                    // NOTES: the global memory type has 64 bits
                    const auto count = static_cast<int>(
                        ptx::ld_volatile<int64_t>(workspace_layout.get_scaleup_rank_expert_count_ptr<false>() + i));
                    const auto decoded = math::encode_decode_positive(count);
                    if (math::is_decoded_positive_ready(decoded)) {
                        workspace_layout.get_scaleup_rank_expert_count_ptr<false>()[i] = 0;
                        rank_expert_count[i] = decoded;
                        return true;
                    }
''', '''            // Wait for rank and expert count
#if EP_TRACE && EP_TRACE_NOTIFY
            if (tr_on and thread_idx == 0) TR[trace::kSM + 5] = trace::now();
#endif
            const auto start_clock = clock64();
            for (int i = thread_idx; i < kNumRanks + kNumExperts; i += kNumNotifyThreads) {
                comm::timeout_while<kNumTimeoutCycles>([=](const bool& is_last_check) {
                    // NOTES: the global memory type has 64 bits
                    const auto count = static_cast<int>(
                        ptx::ld_volatile<int64_t>(RECV_COUNT_PTR() + i));
                    const auto decoded = math::encode_decode_positive(count);
                    if (math::is_decoded_positive_ready(decoded)) {
                        RECV_COUNT_PTR()[i] = 0;
                        rank_expert_count[i] = decoded;
#if EP_TRACE && EP_TRACE_NOTIFY
                        if (tr_on) TR[trace::kRecv + i] = trace::now();
#endif
                        return true;
                    }
''', 'phase F')
    s = sub_once(s, '''            ptx::named_barrier<kNumNotifyThreads>(kNotifyBarrierIndex);

            // Reduce expert count and add stats
''', '''            ptx::named_barrier<kNumNotifyThreads>(kNotifyBarrierIndex);
#if EP_TRACE && EP_TRACE_NOTIFY
            if (tr_on and thread_idx == 0) TR[trace::kSM + 6] = trace::now();
#endif

            // Reduce expert count and add stats
''', 'phase F done')
    s = sub_once(s, '''                __syncwarp();
            }

            // Do prefix sum by the warps
''', '''                __syncwarp();
#if EP_TRACE && EP_TRACE_NOTIFY
                if (tr_on and thread_idx == 0) TR[trace::kSM + 7] = trace::now();
#endif
            }

            // Do prefix sum by the warps
''', 'phase H')

    # receive-count pointer macro (relocation variant)
    s = sub_once(s, '    constexpr int kNumExpertsPerRank = kNumExperts / kNumRanks;\n    EP_STATIC_ASSERT(kNumExperts % kNumRanks == 0, "Invalid number of experts or ranks");\n    EP_STATIC_ASSERT(kNumNotifyWarps % 4 == 0, "Invalid warpgroup size");\n',
'''    constexpr int kNumExpertsPerRank = kNumExperts / kNumRanks;
    EP_STATIC_ASSERT(kNumExperts % kNumRanks == 0, "Invalid number of experts or ranks");
    EP_STATIC_ASSERT(kNumNotifyWarps % 4 == 0, "Invalid warpgroup size");
#if EP_TRACE_RELOCATE_RECV
#define RECV_COUNT_PTR() (reinterpret_cast<int64_t*>(reinterpret_cast<int8_t*>(workspace_layout.signals.scaleout_channel_signaled_tail) + EP_TRACE_RELOCATE_RECV))
#else
#define RECV_COUNT_PTR() (workspace_layout.get_scaleup_rank_expert_count_ptr<false>())
#endif
''', 'recv macro')

    # --- dispatch warps: loop instrumentation ---
    s = sub_once(s, '''        // Iterate all tokens
        const auto token_start = dispatch_warp_idx * kNumSMs + sm_idx;
        const auto token_stride = kNumDispatchWarps * kNumSMs;
        for (int token_idx = token_start; token_idx < num_tokens; token_idx += token_stride) {
            const auto token_i64_idx = static_cast<int64_t>(token_idx);

            // Wait TMA store arrivals
            ptx::tma_store_wait();
            __syncwarp();
''', '''        // Iterate all tokens
        const auto token_start = dispatch_warp_idx * kNumSMs + sm_idx;
        const auto token_stride = kNumDispatchWarps * kNumSMs;
#if EP_TRACE && EP_TRACE_LOOP
        int prev_token_idx = -1;
        const int global_dispatch_warp = sm_idx * kNumDispatchWarps + dispatch_warp_idx;
        if (tr_on and lane_idx == 0) { TR[trace::kWarp + global_dispatch_warp * 4 + 0] = trace::now(); TR[trace::kWarp + global_dispatch_warp * 4 + 3] = (static_cast<int64_t>(trace::smid()) << 32) | sm_idx; }
        int64_t t_slot_wait_start = 0;
#define TOKREC(tok) (TR + trace::kTok + static_cast<int64_t>(tok) * trace::kTokStride)
#endif
        for (int token_idx = token_start; token_idx < num_tokens; token_idx += token_stride) {
            const auto token_i64_idx = static_cast<int64_t>(token_idx);

            // Wait TMA store arrivals
#if EP_TRACE && EP_TRACE_LOOP
            if (tr_on) t_slot_wait_start = trace::now();
#endif
#if EP_TRACE_WAIT_READ
            ptx::tma_store_wait_read();
#else
            ptx::tma_store_wait();
#endif
#if EP_TRACE && EP_TRACE_LOOP
            if (tr_on) {
                const int64_t t_done = trace::now();
                if (prev_token_idx >= 0 and lane_idx < kNumTopk) TOKREC(prev_token_idx)[16 + lane_idx] = t_done;   // per-lane completion of previous token's store
                if (lane_idx == 0) { TOKREC(token_idx)[0] = (static_cast<int64_t>(sm_idx) << 32) | dispatch_warp_idx; TOKREC(token_idx)[1] = t_slot_wait_start; TOKREC(token_idx)[2] = t_done; }
            }
#endif
            __syncwarp();
''', 'loop head')
    s = sub_once(s, '''            } else {
                if (ptx::deduplicate(stored_dst_rank_idx, lane_idx) and stored_dst_rank_idx >= 0)
                    stored_dst_slot_idx = atomicAdd(workspace_layout.get_scaleup_atomic_sender_counter() + stored_dst_rank_idx, 1);
                if (lane_idx < kNumTopk) {
''', '''            } else {
#if EP_TRACE && EP_TRACE_LOOP
                const int64_t t_atomic_start = tr_on ? trace::now() : 0;
#endif
                if (ptx::deduplicate(stored_dst_rank_idx, lane_idx) and stored_dst_rank_idx >= 0)
                    stored_dst_slot_idx = atomicAdd(workspace_layout.get_scaleup_atomic_sender_counter() + stored_dst_rank_idx * trace::kCounterStride, 1);
#if EP_TRACE && EP_TRACE_LOOP
                if (tr_on) {
                    const int64_t t_atomic_end = trace::now();
                    if (lane_idx == 0) TOKREC(token_idx)[3] = t_atomic_start;
                    if (lane_idx < kNumTopk) { TOKREC(token_idx)[40 + lane_idx] = stored_dst_slot_idx >= 0 ? t_atomic_end : 0; TOKREC(token_idx)[24 + lane_idx] = stored_dst_rank_idx; TOKREC(token_idx)[32 + lane_idx] = stored_dst_slot_idx; }
                }
#endif
                if (lane_idx < kNumTopk) {
''', 'atomic')
    s = sub_once(s, '''            if (ptx::elect_one_sync()) {
                ptx::mbarrier_arrive_and_set_tx(mbarrier_ptr, kNumHiddenBytes);
                ptx::mbarrier_wait_and_flip_phase(mbarrier_ptr, phase);
            }
            __syncwarp();

            // TMA store to send buffer
''', '''            if (ptx::elect_one_sync()) {
                ptx::mbarrier_arrive_and_set_tx(mbarrier_ptr, kNumHiddenBytes);
                ptx::mbarrier_wait_and_flip_phase(mbarrier_ptr, phase);
            }
            __syncwarp();
#if EP_TRACE && EP_TRACE_LOOP
            if (tr_on and lane_idx == 0) TOKREC(token_idx)[5] = trace::now();
#endif

            // TMA store to send buffer
''', 'load done')
    s = sub_once(s, '''            if (dst_ptr != nullptr)
                ptx::tma_store_1d(dst_ptr, tma_buffer.get_base_ptr(), tma_buffer.get_num_bytes<false>());
            ptx::tma_store_commit();
            __syncwarp();
''', '''            if (dst_ptr != nullptr)
                ptx::tma_store_1d(dst_ptr, tma_buffer.get_base_ptr(), tma_buffer.get_num_bytes<false>());
            ptx::tma_store_commit();
#if EP_TRACE && EP_TRACE_LOOP
            if (tr_on) {
                const int64_t t_issue = trace::now();
                const unsigned issue_mask = ptx::gather(dst_ptr != nullptr);  // warp-wide, must not be inside a lane branch
                if (lane_idx < kNumTopk) TOKREC(token_idx)[8 + lane_idx] = dst_ptr != nullptr ? t_issue : 0;
                if (lane_idx == 0) { TOKREC(token_idx)[6] = t_issue; TOKREC(token_idx)[7] = issue_mask; }
                prev_token_idx = token_idx;
            }
#endif
            __syncwarp();
''', 'store issue')
    # end of loop: per-lane completion of the last token, warp done
    s = sub_once(s, '''                __syncwarp();
            }
        }
    }

    // Barrier to ensure data arrival
''', '''                __syncwarp();
            }
        }
#if EP_TRACE && EP_TRACE_LOOP
        if (tr_on) {
            ptx::tma_store_wait();
            const int64_t t_done = trace::now();
            if (prev_token_idx >= 0 and lane_idx < kNumTopk) TOKREC(prev_token_idx)[16 + lane_idx] = t_done;
            if (lane_idx == 0) { TR[trace::kWarp + global_dispatch_warp * 4 + 1] = t_done; TR[trace::kWarp + global_dispatch_warp * 4 + 2] = prev_token_idx >= 0 ? (prev_token_idx - token_start) / token_stride + 1 : 0; }
        }
#endif
    }

    // Barrier to ensure data arrival
#if EP_TRACE && EP_TRACE_SM
    if (tr_on and thread_idx == 0) TR[trace::kSM + sm_idx * 32 + 9] = trace::now();
#endif
''', 'loop end')
    s = sub_once(s, '''    // Trigger the copy epilogue kernel
    cudaTriggerProgrammaticLaunchCompletion();

    // Clean atomic counters
    EP_STATIC_ASSERT(kNumRanks <= kNumThreads, "Insufficient threads");
    if (not kReuseSlotIndices and sm_idx == 0 and thread_idx < kNumRanks)
        workspace_layout.get_scaleup_atomic_sender_counter()[thread_idx] = 0;
}
''', '''#if EP_TRACE && EP_TRACE_SM
    if (tr_on and thread_idx == 0) TR[trace::kSM + sm_idx * 32 + 10] = trace::now();
#endif
    // Trigger the copy epilogue kernel
    cudaTriggerProgrammaticLaunchCompletion();

    // Clean atomic counters
    EP_STATIC_ASSERT(kNumRanks <= kNumThreads, "Insufficient threads");
    if (not kReuseSlotIndices and sm_idx == 0 and thread_idx < kNumRanks)
        workspace_layout.get_scaleup_atomic_sender_counter()[thread_idx * trace::kCounterStride] = 0;
#if EP_TRACE && EP_TRACE_SM
    if (tr_on and thread_idx == 0) TR[trace::kSM + sm_idx * 32 + 11] = trace::now();
#endif
}
''', 'kernel end')

    open(PKG, 'w').write(s)
    print(f'patched {PKG}: trace={TRACE} wait_read={a.wait_read} pad_counters={a.pad_counters} relocate_recv={a.relocate_recv}')


if __name__ == '__main__':
    main()
